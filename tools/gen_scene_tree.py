#!/usr/bin/env python3
import pathlib, sys

DEPTH = 6
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "resources/ui/components/scene_tree.rml"

RUN_ATTRS = ('data-style-font-weight="{r}.weight" data-style-font-style="{r}.style" '
             'data-style-background-color="{r}.background" data-style-display="{r}.display" '
             'data-style-width="{r}.width" data-style-overflow="{r}.overflow"')


def runs(var, src, ind):
    r = var
    plain = RUN_ATTRS.format(r=r)
    return (f'{ind}<span data-for="{r} : {src}"><span data-if="{r}.colored == \'1\' "><span data-style-color="{r}.color" {plain}>'
            f'{{{{{r}.text}}}}</span></span><span data-if="{r}.colored != \'1\' "><span {plain}>{{{{{r}.text}}}}</span></span></span>\n').replace("'1' \"", "'1'\"")


def level(n, depth, ind, source):
    p = "  "
    out = []
    a = out.append
    a(f'{ind}<div data-for="{n} : {source}" data-attr-id="{n}.id" data-attr-class="\'n \' + {n}.cls"\n')
    a(f'{ind}    data-style-left="{n}.x + \'px\'" data-style-top="{n}.y + \'px\'"\n')
    a(f'{ind}    data-style-width="{n}.w > 0 ? {n}.w + \'px\' : \'auto\'" data-style-height="{n}.h > 0 ? {n}.h + \'px\' : \'auto\'" data-style-z-index="{n}.z"\n')
    a(f'{ind}    data-attr-snd="{n}.snd" data-attr-vol="{n}.vol" data-attr-pit="{n}.pit">\n')
    i = ind + p
    a(f'{i}<mcimg data-if="{n}.kind == 1" data-attr-src="{n}.src" data-attr-uv="{n}.uv" data-attr-nine="{n}.nine"\n')
    a(f'{i}    data-attr-tiled="{n}.tiled" data-attr-tilescale="{n}.tileScale" data-attr-clip="{n}.clipDirection"\n')
    a(f'{i}    data-attr-color="{n}.tint" data-attr-alpha="{n}.alpha" data-attr-keep="{n}.keep"></mcimg>\n')
    a(f'{i}<mcitem data-if="{n}.kind == 2" data-attr-key="{n}.key" data-attr-alpha="{n}.alpha" data-attr-glint="{n}.glint"></mcitem>\n')
    a(f'{i}<div data-if="{n}.kind == 3" class="tx" data-style-font-family="{n}.family" data-style-font-size="{n}.size + \'px\'"\n')
    a(f'{i}    data-style-line-height="{n}.lineHeight + \'px\'" data-style-text-align="{n}.align" data-style-color="{n}.color">\n')
    a(runs(f"{n}r", f"{n}.runs", i + p))
    a(f'{i}</div>\n')
    a(f'{i}<div data-if="{n}.kind == 7" class="lab">\n')
    a(runs(f"{n}l", f"{n}.runs", i + p))
    a(f'{i}</div>\n')
    a(f'{i}<div data-if="{n}.kind == 4" class="fill" data-style-background-color="{n}.color"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 5" class="fill" data-style-decorator="{n}.decorator"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 6" class="ul"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 8" class="rim" data-style-width="({n}.w - 3) + \'px\'"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 8" class="face" data-style-width="({n}.w - 4) + \'px\'"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 8" class="shade" data-style-width="({n}.w - 2) + \'px\'"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 8" class="edge" data-style-left="({n}.w - 2) + \'px\'"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 8" class="lbl" data-style-width="{n}.w + \'px\'">\n')
    a(runs(f"{n}b", f"{n}.runs", i + p))
    a(f'{i}</div>\n')
    a(f'{i}<div data-if="{n}.kind == 9" class="rim" data-style-width="({n}.w - 3) + \'px\'"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 9" class="face" data-style-width="({n}.w - 4) + \'px\'"></div>\n')
    a(f'{i}<div data-if="{n}.kind == 9" class="lbl" data-style-width="{n}.w + \'px\'" style="z-index: 2;">\n')
    a(runs(f"{n}s", f"{n}.runs", i + p))
    a(f'{i}</div>\n')
    a(f'{i}<div data-if="{n}.kind == 9" class="knob" data-style-left="{n}.knob + \'px\'" style="top: 0px;"><div class="krim"></div><div class="kface"></div><div class="kshade"></div></div>\n')
    if depth < DEPTH:
        child = f"{n[0]}{depth + 1}" if n == "n" else f"n{depth + 1}"
        a(level(child, depth + 1, i, f"{n}.children"))
    a(f'{ind}</div>\n')
    return "".join(out)


def build():
    head = "<!-- Scene node tree: renders the named node list, nested six levels deep. Include with |list=<name>. Generated by tools/gen_scene_tree.py. -->\n"
    return head + level("n", 0, "", "{{list}}")


if __name__ == "__main__":
    text = build()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
