"""Export numerical range-reduction coefficients, never executable bytes."""

import argparse
import hashlib
import json
import struct
from pathlib import Path

from generate import INPUT_SHA256


def generate(data):
    if data["input_sha256"] != INPUT_SHA256 or data["input_name"] != "Windows Server 1.26.10":
        raise ValueError("Wrong BDS reference")
    pages = {}
    for function in data["functions"].values():
        for address, value in function["pages"].items():
            if address in pages and pages[address] != bytes.fromhex(value):
                raise ValueError("Inconsistent exported data")
            pages[address] = bytes.fromhex(value)

    def read(address, size):
        return bytes(pages[hex(ea & ~4095)][ea & 4095] for ea in range(address, address + size))

    lines = ["#pragma once", "", "#include <array>", "#include <cstdint>", "",
             "// Numerical coefficients for BDS vector sinf's full finite range.",
             "// Generated by tools/bds_reference/trig_constants.py; no code bytes.",
             f"// Reference input SHA-256: {INPUT_SHA256}",
             "namespace perlin::physics::bds::detail {", "    // clang-format off"]
    for name, address, count in (("SineReductionWords", 0x1477DE500 + 140 * 12, 115 * 3),
                                  ("SineReconstructionWords", 0x1477DF100, 1024)):
        raw = read(address, count * 4)
        words = struct.unpack('<' + 'I' * count, raw)
        lines.append(f"    // {address:#x}; numerical table SHA-256: {hashlib.sha256(raw).hexdigest()}")
        lines.append(f"    inline constexpr std::array<uint32_t, {count}> {name}{{{{")
        for offset in range(0, count, 8):
            lines.append("        " + ", ".join(f"0x{word:08x}u" for word in words[offset:offset + 8]) + ",")
        lines.extend(("    }};", ""))
    lines.extend(("    // clang-format on", "}"))
    return '\n'.join(lines) + '\n'


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--export', required=True, type=Path)
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args()
    args.out.write_text(generate(json.loads(args.export.read_text())))
