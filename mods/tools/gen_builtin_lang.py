#!/usr/bin/env python3
import os
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
t=open(os.path.join(root,'resources/perlin_en_US.lang'),encoding='utf8').read()
lines=[l for l in t.split('\n') if l and not l.startswith('##')]
esc=lambda s:s.replace('\\','\\\\').replace('"','\\"')
body=''.join('    "%s\\n"\n'%esc(l) for l in lines)
open(os.path.join(root,'src/client/i18n/BuiltinEnglish.cpp'),'w',encoding='utf8').write('// Generated by tools/gen_builtin_lang.py from resources/perlin_en_US.lang.\n#include "client/i18n/BuiltinEnglish.hpp"\n\nnamespace perlin::i18n {\n    const char* BuiltinEnglish() {\n        return\n'+body+'            ;\n    }\n}\n')
