#!/usr/bin/env python3
"""Embeds resources/death_screen.rml into src/client/ui/DeathScreenDefault.cpp so the default needs no file on disk."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
text = (root / "resources" / "death_screen.rml").read_text(encoding="utf-8")
chunks = [text[i:i + 6000] for i in range(0, len(text), 6000)]
out = ['// Generated by tools/gen_death_rml.py from resources/death_screen.rml. Do not edit.',
       '#include "client/ui/DeathScreen.hpp"', '', 'namespace perlin::ui {',
       '    std::string EmbeddedDeathScreenTemplate() {', '        std::string t;']
for c in chunks:
    out.append('        t += R"PERLINRML(' + c + ')PERLINRML";')
out += ['        return t;', '    }', '}', '']
(root / "src/client/ui/DeathScreenDefault.cpp").write_text("\n".join(out), encoding="utf-8")
