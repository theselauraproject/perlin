"""Bake the overworld biome placement table and the biome surface materials into a c++ source:
gen_biome_tables.py <overworld_biomes_26_3.txt> <bedrock-samples dir> <out.cpp>

Two sources, joined by a name map:
  - where each biome goes: Java's OverworldBiomeBuilder, dumped by tools/javaref/BiomeDump.java as 7594 (climate box, biome) rows. Neither bedrock-samples nor
    the dedicated server package has a placement table, so these values are hardcoded from Java.
  - what each biome is made of: bedrock-samples' behavior_pack/biomes/*.biome.json, minecraft:surface_builder (top / mid / foundation / sea floor material,
    sea floor depth, builder type).
The output is deterministic and committed; nothing reads either source at run time.
"""
import glob
import json
import os
import sys

dump, samples, out = sys.argv[1:4]

# java overworld biome -> bedrock biome identifier (bedrock kept most of the pre-1.18 names)
JAVA_TO_BEDROCK = {
    'desert': 'desert', 'forest': 'forest', 'plains': 'plains', 'snowy_plains': 'ice_plains', 'savanna': 'savanna', 'taiga': 'taiga', 'beach': 'beach',
    'grove': 'grove', 'snowy_taiga': 'cold_taiga', 'wooded_badlands': 'mesa_plateau_stone', 'badlands': 'mesa', 'jungle': 'jungle',
    'windswept_savanna': 'savanna_mutated', 'snowy_slopes': 'snowy_slopes', 'meadow': 'meadow', 'dark_forest': 'roofed_forest', 'eroded_badlands': 'mesa_bryce',
    'windswept_forest': 'extreme_hills_plus_trees', 'savanna_plateau': 'savanna_plateau', 'jagged_peaks': 'jagged_peaks', 'frozen_peaks': 'frozen_peaks',
    'windswept_hills': 'extreme_hills', 'old_growth_pine_taiga': 'mega_taiga', 'snowy_beach': 'cold_beach', 'bamboo_jungle': 'bamboo_jungle',
    'ice_spikes': 'ice_plains_spikes', 'old_growth_spruce_taiga': 'redwood_taiga_mutated', 'birch_forest': 'birch_forest',
    'windswept_gravelly_hills': 'extreme_hills_mutated', 'dappled_forest': 'dappled_forest', 'sparse_jungle': 'jungle_edge', 'stony_peaks': 'stony_peaks',
    'flower_forest': 'flower_forest', 'sunflower_plains': 'sunflower_plains', 'old_growth_birch_forest': 'birch_forest_mutated', 'cherry_grove': 'cherry_grove',
    'pale_garden': 'pale_garden', 'swamp': 'swampland', 'mangrove_swamp': 'mangrove_swamp', 'stony_shore': 'stone_beach', 'frozen_river': 'frozen_river',
    'river': 'river', 'warm_ocean': 'warm_ocean', 'ocean': 'ocean', 'mushroom_fields': 'mushroom_island', 'lukewarm_ocean': 'lukewarm_ocean',
    'frozen_ocean': 'frozen_ocean', 'deep_ocean': 'deep_ocean', 'deep_lukewarm_ocean': 'deep_lukewarm_ocean', 'deep_frozen_ocean': 'deep_frozen_ocean',
    'deep_cold_ocean': 'deep_cold_ocean', 'cold_ocean': 'cold_ocean', 'sulfur_caves': 'sulfur_caves', 'lush_caves': 'lush_caves',
    'dripstone_caves': 'dripstone_caves', 'deep_dark': 'deep_dark',
}

bedrock = {}
for f in sorted(glob.glob(os.path.join(samples, 'behavior_pack', 'biomes', '*.biome.json'))):
    j = json.load(open(f))['minecraft:biome']
    ident = j['description']['identifier'].replace('minecraft:', '')
    builder = j['components'].get('minecraft:surface_builder', {}).get('builder', {})
    bedrock[ident] = builder

rows = []
for line in open(dump):
    parts = line.split()
    if len(parts) != 14:
        continue
    rows.append(([int(v) for v in parts[:13]], parts[13].replace('minecraft:', '')))

names = []
for _, n in rows:
    if n not in names:
        names.append(n)
missing = [n for n in names if n not in JAVA_TO_BEDROCK or JAVA_TO_BEDROCK[n] not in bedrock]
if missing:
    sys.exit('no bedrock biome for: ' + ', '.join(missing))

BUILDERS = {'minecraft:overworld': 0, 'minecraft:frozen_ocean': 1, 'minecraft:mesa': 2, 'minecraft:swamp': 3}
def block(b, key, fallback):
    v = b.get(key, fallback)
    return v if v.startswith('minecraft:') else 'minecraft:' + v

with open(out, 'w') as f:
    f.write('// generated by tools/gen_biome_tables.py (java biome placement + bedrock-samples surface materials); do not edit\n')
    f.write('#include "world/vanilla/BiomeData.hpp"\n\nnamespace perlin::server::vanilla {\n')
    f.write(f'    extern const int kBiomePointCount = {len(rows)};\n')
    f.write('    // per point: temperature, humidity, continentalness, erosion, depth, weirdness as (min, max) pairs, then the offset; values are climate * 10000\n')
    f.write('    extern const int16_t kBiomePointData[] = {\n')
    for i, (v, _) in enumerate(rows):
        f.write('        ' + ','.join(str(x) for x in v) + (',\n' if i + 1 < len(rows) else '\n'))
    f.write('    };\n')
    f.write('    extern const uint8_t kBiomePointBiome[] = {\n')
    for i in range(0, len(rows), 40):
        chunk = rows[i:i + 40]
        f.write('        ' + ','.join(str(names.index(n)) for _, n in chunk) + (',\n' if i + 40 < len(rows) else '\n'))
    f.write('    };\n')
    f.write(f'    extern const int kBiomeCount = {len(names)};\n')
    f.write('    extern const BiomeMaterials kBiomes[] = {\n')
    for n in names:
        b = bedrock[JAVA_TO_BEDROCK[n]]
        kind = BUILDERS.get(b.get('type', 'minecraft:overworld'), 0)
        f.write(f'        {{"{n}", "{JAVA_TO_BEDROCK[n]}", "{block(b, "top_material", "minecraft:grass_block")}", "{block(b, "mid_material", "minecraft:dirt")}", '
                f'"{block(b, "foundation_material", "minecraft:stone")}", "{block(b, "sea_floor_material", "minecraft:gravel")}", "{block(b, "sea_material", "minecraft:water")}", '
                f'{int(b.get("sea_floor_depth", 7))}, {kind}}},\n')
    f.write('    };\n}\n')
print(len(rows), 'points,', len(names), 'biomes')
